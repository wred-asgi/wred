"""Rebuild the static documentation search index using only the standard library.

Run from any directory with: python docs/tutorial/build_search.py
The HTML pages remain directly usable without running a build or a web server.
"""

from html.parser import HTMLParser
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent


class PageText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_main = False
        self.in_h1 = False
        self.text = []
        self.title = []
        self.headings = []
        self.heading = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'main':
            self.in_main = True
        if not self.in_main:
            return
        if tag == 'h1':
            self.in_h1 = True
        if tag in ('h2', 'h3') and attrs.get('id'):
            self.heading = {'anchor': attrs.get('id', ''), 'parts': []}

    def handle_endtag(self, tag):
        if tag == 'main':
            self.in_main = False
        if tag == 'h1':
            self.in_h1 = False
        if tag in ('h2', 'h3') and self.heading:
            self.headings.append({
                'anchor': self.heading['anchor'],
                'title': ''.join(self.heading['parts']),
            })
            self.heading = None

    def handle_data(self, data):
        if not self.in_main:
            return
        self.text.append(data)
        if self.in_h1:
            self.title.append(data)
        if self.heading:
            self.heading['parts'].append(data)


def main():
    pages = []
    for path in sorted(ROOT.glob('*.html')):
        parser = PageText()
        parser.feed(path.read_text())
        pages.append({
            'url': path.name,
            'title': ''.join(parser.title),
            'headings': parser.headings,
            'text': re.sub(r'\s+', ' ', ' '.join(parser.text)).strip(),
        })
    payload = json.dumps(pages, ensure_ascii=False, separators=(',', ':'))
    (ROOT / 'search-index.js').write_text(
        '// Generated by build_search.py; edit the HTML pages, then rebuild.\n'
        f'const DOCS_SEARCH_INDEX = {payload};\n'
    )
    print(f'Indexed {len(pages)} documentation pages.')


if __name__ == '__main__':
    main()
